async (page) => {
  const passed = [], errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto("http://127.0.0.1:8879/#campaign?tab=world"); await page.reload();
  const check = (value, message) => { if (!value) throw Error(message); };
  const button = (name) => page.getByRole("button", { name, exact: true });
  const field = (path) => page.locator('[data-campaign-path="' + path + '"]');
  const stored = () => page.evaluate(() => JSON.parse(localStorage.getItem("d20-studio-blueprint-v1")));
  const save = async () => { await page.locator("[data-campaign-save]").click(); await page.locator("[data-campaign-apply]").click(); };
  await page.getByRole("heading", {name:"Mondo",exact:true,level:1}).waitFor();
  await page.locator('[data-campaign-new="world"]').click();
  await field("data.title").fill("Faro di Bruma");
  await field("data.body").fill("Il faro custodisce un approdo noto a tutto il gruppo.");
  await field("data.worldType").selectOption("place");
  await page.locator('[data-campaign-access-mode="access"]').selectOption("campaign");
  await page.getByText("Sezioni con destinatari propri", {exact:true}).click();
  await page.locator("[data-campaign-add-section]").click();
  check(await field("data.sections.0.title").isVisible(), "Adding a section closed its editor");
  await field("data.sections.0.title").fill("Passaggio segreto personale");
  await field("data.sections.0.body").fill("La chiave privata è sotto il terzo gradino.");
  await save();
  await page.getByRole("heading", {name:"Faro di Bruma",exact:true,level:1}).waitFor();
  let state = await stored();
  const world = state.campaignContent.entries.findLast((entry) => entry.kind === "world" && entry.revisions.at(-1).data.title === "Faro di Bruma");
  check(world, "World entry was not saved");
  await page.locator("#demo-role").selectOption("dm");
  check((await page.locator("#content").innerText()).includes("approdo"), "Campaign entry unavailable to a reader");
  check(!(await page.locator("#content").innerText()).includes("terzo gradino"), "Secret section body leaked");
  check(!(await page.locator("#content").innerText()).includes("Passaggio segreto"), "Secret section title leaked");
  check(!(await page.locator("[data-campaign-edit]").count()), "Reader received edit rights from DM role");
  await page.locator("#demo-role").selectOption("player");
  await page.locator('[data-campaign-tab="journal"]').click();
  await page.locator('[data-campaign-new="recap"]').click();
  await field("data.title").fill("La luce ritrovata");
  await field("data.body").fill("Abbiamo raggiunto il faro e incontrato la cartografa. Nessun riposo è stato applicato.");
  await page.locator('[data-campaign-access-mode="access"]').selectOption("campaign");
  await page.getByText("Collegamenti a voci", {exact:true}).click();
  await page.locator("[data-campaign-link-choice]").selectOption(world.id);
  await page.locator("[data-campaign-add-link]").click();
  await save();
  await page.getByRole("heading", {name:"La luce ritrovata",exact:true,level:1}).waitFor();
  state = await stored();
  const recap = state.campaignContent.entries.findLast((entry) => entry.kind === "recap" && entry.revisions.at(-1).data.title === "La luce ritrovata");
  check(recap.revisions.at(-1).data.links.some((link) => link.id === world.id), "Recap link was not stored");
  passed.push("Shared world entry keeps its private section hidden; recap links the same accessible entry");
  await button("Inizio").click();
  await page.getByRole("heading", {name:"La prossima avventura",exact:true,level:1}).waitFor();
  check((await page.locator("#content").innerText()).includes("La luce ritrovata"), "Home did not show latest readable recap");
  await page.locator('[data-home-recap="' + recap.id + '"]').click();
  await page.getByRole("heading", {name:"La luce ritrovata",exact:true,level:1}).waitFor();
  await page.locator('.campaign-links [data-campaign-route]').click();
  await page.getByRole("heading", {name:"Faro di Bruma",exact:true,level:1}).waitFor();
  await page.locator("[data-campaign-return]").click();
  await page.getByRole("heading", {name:"La luce ritrovata",exact:true,level:1}).waitFor();
  const beforeTable = await stored();
  await button("Entra al Tavolo").click(); await page.locator("#battle-map").waitFor();
  await button("Torna alla campagna").click();
  await page.getByRole("heading", {name:"Panoramica",exact:true,level:1}).waitFor();
  state = await stored();
  check(JSON.stringify(state.actors) === JSON.stringify(beforeTable.actors), "Navigating recap/world/table changed characters");
  check(JSON.stringify(state.combat) === JSON.stringify(beforeTable.combat), "Returning from Table ended or changed combat");
  passed.push("Home recap → linked place → return → Table → campaign preserves narrative context and game state");
  await page.screenshot({path:"/Users/salvatoredicara/Workspace/Codex/d20-blueprint-evidence/2026-09-23/campaign-hub-desktop-it.png",fullPage:true});
  check(errors.length === 0, "Runtime errors: " + errors.join("; "));
  return {passed,errors};
}
