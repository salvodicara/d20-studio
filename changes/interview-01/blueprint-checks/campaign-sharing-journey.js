async (page) => {
  const passed = [], errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto("http://127.0.0.1:8879/#notes"); await page.reload();
  const check = (value, message) => { if (!value) throw Error(message); };
  const button = (name) => page.getByRole("button", {name,exact:true});
  const field = (path) => page.locator('[data-campaign-path="' + path + '"]');
  const stored = () => page.evaluate(() => JSON.parse(localStorage.getItem("d20-studio-blueprint-v1")));
  const title = "Indizi condivisi della cartografa";
  const waitDetail = () => page.getByRole("heading",{name:title,exact:true,level:1}).waitFor();
  const apply = async () => { await page.locator("[data-campaign-save]").click(); await page.locator("[data-campaign-apply]").click(); await waitDetail(); };
  const access = async (mode, grant) => { await page.locator("[data-campaign-access]").click(); await page.locator('#dialog [name="mode"]').selectOption(mode); if(grant) await page.locator('#dialog [name="grant-dm"]').selectOption(grant); await button("Salva accessi").click(); };
  await page.locator('[data-campaign-new="note"]').click();
  await page.locator("[data-campaign-context]").selectOption("lanterns");
  await field("data.title").fill(title); await field("data.body").fill("Versione iniziale personale e non condivisibile."); await apply();
  let state = await stored();
  const note = state.campaignContent.entries.findLast((entry) => entry.kind === "note" && entry.revisions.at(-1).data.title === title);
  const oldRevision = note.currentRevisionId;
  await page.locator("[data-campaign-edit]").click();
  await field("data.body").fill("Indizi da condividere con il DM."); await apply();
  await access("selected", "read");
  await page.locator("#demo-role").selectOption("dm"); await waitDetail();
  check(!(await page.locator("[data-campaign-edit]").count()), "Reader can edit from DM role");
  // P9 CA-82: the versions a reader may see are listed in «Cronologia».
  await page.locator("#content [data-campaign-timeline]").click();
  check(!(await page.locator('#dialog [data-campaign-history="' + oldRevision + '"]').count()), "Sharing exposed previous private history");
  await page.keyboard.press("Escape");
  check((await page.locator("#content").innerText()).includes("Indizi da condividere"), "New reader cannot read explicitly shared current text");
  await page.locator("#demo-role").selectOption("player"); await access("selected", "edit");
  await page.locator("#demo-role").selectOption("dm");
  await page.locator("[data-campaign-edit]").click();
  await field("data.body").fill("Contributo salvato dal collaboratore DM."); await apply();
  check(!(await page.locator("[data-campaign-access]").count()), "Editing granted owner access controls");
  await page.locator("#demo-role").selectOption("player"); await access("private");
  await page.locator("#demo-role").selectOption("dm");
  check(!(await page.locator("#content").innerText()).includes("Contributo salvato"), "Revoked reader retains rendered content");
  await page.locator("#demo-role").selectOption("player"); await waitDetail();
  check((await page.locator("#content").innerText()).includes("Contributo salvato dal collaboratore"), "Revocation erased saved contribution");
  passed.push("Read/edit/access remain distinct; sharing excludes old private history, and revocation preserves saved contributions");
  await page.locator("[data-campaign-edit]").click();
  await field("data.body").fill("Bozza salvabile offline, condivisione da riconfermare.");
  await page.locator('[data-campaign-access-mode="access"]').selectOption("selected");
  await page.locator('[data-campaign-grant="dm"][data-access-path="access"]').selectOption("read");
  await button("Preferenze").click(); await page.locator('#dialog [name="offline"]').check(); await button("Salva preferenze").click();
  await page.locator("[data-campaign-save]").click();
  await page.locator("[data-campaign-apply]").click();
  check((await field("data.body").inputValue()).includes("Bozza salvabile offline"), "Offline error lost input");
  state = await stored();
  check(state.campaignContent.entries.find((entry) => entry.id === note.id).access.mode === "private", "Offline sharing falsely succeeded");
  await button("Preferenze").click(); await page.locator('#dialog [name="offline"]').uncheck(); await button("Salva preferenze").click();
  await page.locator("[data-campaign-apply]").click(); await waitDetail();
  state = await stored(); check(state.campaignContent.entries.find((entry) => entry.id === note.id).access.mode === "selected", "Online revalidated sharing failed");
  passed.push("Offline permits private draft recovery but blocks shared apply without losing text; reconnect applies after validation");
  const conflictDraftId = await page.evaluate(async (entryId) => {
    const c = await import('/campaign-content.mjs');
    const state = JSON.parse(localStorage.getItem('d20-studio-blueprint-v1'));
    const mine = c.createCampaignDraft(state,{id:crypto.randomUUID(),entryId},'player');
    c.saveCampaignDraft(state,mine.id,{data:{...mine.data,body:'La mia bozza concorrente da conservare.'},expectedDraftRevision:mine.revision},'player');
    const other = c.createCampaignDraft(state,{id:crypto.randomUUID(),entryId},'player');
    c.saveCampaignDraft(state,other.id,{data:{...other.data,body:'Versione salvata in un’altra visita sintetica.'},expectedDraftRevision:other.revision},'player');
    c.applyCampaignDraft(state,other.id,{reviewKey:c.previewCampaignDraft(state,other.id,'player').reviewKey},'player');
    localStorage.setItem('d20-studio-blueprint-v1',JSON.stringify(state)); return mine.id;
  }, note.id);
  await page.goto('http://127.0.0.1:8879/#notes?tab=edit&id=' + conflictDraftId); await page.reload();
  await field("data.body").waitFor();
  check((await field("data.body").inputValue()).includes("mia bozza concorrente"), "Conflict did not retain saved draft");
  check(await page.locator("[data-campaign-apply]").isDisabled(), "Conflicting draft applied silently");
  check((await page.locator(".campaign-preview").innerText()).includes("altra visita sintetica"), "Conflict comparison omitted current text");
  await page.locator("[data-campaign-rebase]").click();
  await page.locator("[data-campaign-apply]").click(); await waitDetail();
  check((await page.locator("#content").innerText()).includes("mia bozza concorrente"), "Explicit reconciliation lost chosen text");
  passed.push("Domain-generated concurrent revision survives reload; UI compares and explicitly reapplies the preserved draft");
  check(errors.length === 0, "Runtime errors: " + errors.join("; "));
  return {passed,errors};
}
