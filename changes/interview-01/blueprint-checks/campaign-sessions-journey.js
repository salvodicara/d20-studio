async (page) => {
  const passed = [], errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  if (await page.locator("[data-campaign-save]").count()) await page.locator("[data-campaign-save]").click();
  await page.goto("http://127.0.0.1:8879/#campaign?tab=sessions"); await page.reload();
  const check = (value, message) => { if (!value) throw Error(message); };
  const button = (name) => page.getByRole("button", { name, exact: true });
  const field = (path) => page.locator('[data-campaign-path="' + path + '"]');
  const stored = () => page.evaluate(() => JSON.parse(localStorage.getItem("d20-studio-blueprint-v1")));
  const save = async () => { await page.locator("[data-campaign-save]").click(); await page.locator("[data-campaign-apply]").click(); await page.getByRole("heading",{name:"Sessioni",exact:true,level:1}).waitFor(); };
  await page.getByRole("heading",{name:"Sessioni",exact:true,level:1}).waitFor();
  await page.locator("#demo-role").selectOption("dm");
  const before = await stored();
  await page.locator('[data-campaign-new-session="direct"]').click();
  await field("data.title").fill("Partita di ottobre");
  await field("data.localTime").fill("2026-10-09T21:00");
  await field("data.timeZone").fill("Europe/Rome");
  await page.locator("[data-campaign-save]").click();
  let state = await stored();
  check(state.campaign.sessions.length === before.campaign.sessions.length, "Saving draft confirmed appointment");
  check((await page.locator(".campaign-preview").innerText()).includes("Europe/Rome"), "Preview omitted declared timezone");
  await page.locator("[data-campaign-apply]").click();
  await page.getByRole("heading",{name:"Sessioni",exact:true,level:1}).waitFor();
  state = await stored();
  const direct = state.campaign.sessions.findLast((session) => session.title === "Partita di ottobre");
  check(direct.startsAt === "2026-10-09T19:00:00.000Z", "Local appointment resolved to wrong instant");
  await page.locator('[data-campaign-change-session="' + direct.id + '"]').click();
  await field("data.localTime").fill("2026-10-10T21:30"); await save();
  state = await stored();
  check(state.campaign.sessions.find((session) => session.id === direct.id).startsAt === "2026-10-10T19:30:00.000Z", "Explicit date change failed");
  await page.locator('[data-campaign-cancel-session="' + direct.id + '"]').click();
  await field("data.reason").fill("Rinviata dal gruppo, esempio sintetico"); await save();
  state = await stored();
  check(state.campaign.sessions.find((session) => session.id === direct.id).status === "cancelled", "Cancellation removed or failed to mark appointment");
  passed.push("Agreed date previews timezone before confirming, then explicitly changes and cancels the same appointment");
  await page.locator('[data-campaign-new-session="poll"]').click();
  await field("data.title").fill("Scegliamo la prossima serata");
  await page.locator("[data-campaign-add-slot]").click();
  await field("data.slots.0.localTime").fill("2026-10-16T21:00");
  await field("data.slots.0.timeZone").fill("Europe/Rome");
  await page.locator("[data-campaign-add-slot]").click();
  await field("data.slots.1.localTime").fill("2026-10-17T21:00");
  await field("data.slots.1.timeZone").fill("Europe/Rome"); await save();
  state = await stored();
  const poll = state.campaign.polls.findLast((entry) => entry.title === "Scegliamo la prossima serata");
  const slot = poll.slots[0];
  const response = () => page.locator('[data-campaign-response="' + poll.id + '"][data-slot-id="' + slot.id + '"]');
  const withdraw = () => page.locator('[data-campaign-withdraw="' + poll.id + '"][data-slot-id="' + slot.id + '"]');
  await page.locator("#demo-role").selectOption("player");
  check((await response().inputValue()) === "", "No response was prefilled as No");
  check(!(await page.locator("[data-campaign-confirm-slot]").count()), "Ordinary player can confirm poll");
  await response().selectOption("yes");
  await response().selectOption("maybe");
  await withdraw().click();
  state = await stored();
  check(!state.campaign.polls.find((entry) => entry.id === poll.id).responses.player?.[slot.id], "Withdraw did not remove own response");
  await response().selectOption("yes");
  await page.locator("#demo-role").selectOption("dm");
  await response().selectOption("yes");
  state = await stored();
  check(state.campaign.sessions.length === before.campaign.sessions.length + 1, "Consensus automatically scheduled a session");
  await page.locator('[data-campaign-confirm-slot="' + poll.id + '"][data-slot-id="' + slot.id + '"]').click();
  await page.locator("[data-campaign-apply]").click();
  await page.getByRole("heading",{name:"Sessioni",exact:true,level:1}).waitFor();
  state = await stored();
  const confirmedPoll = state.campaign.polls.find((entry) => entry.id === poll.id);
  check(confirmedPoll.status === "confirmed", "Explicit organizer confirmation failed");
  check(state.campaign.sessions.length === before.campaign.sessions.length + 2, "Confirmation duplicated or lost a session");
  check(JSON.stringify(state.actors) === JSON.stringify(before.actors), "Scheduling changed resources");
  check(JSON.stringify(state.combat) === JSON.stringify(before.combat), "Scheduling changed combat");
  check(JSON.stringify(state.campaignContent.entries) === JSON.stringify(before.campaignContent.entries), "Scheduling changed recaps or notes");
  passed.push("Optional poll keeps missing answers distinct, lets each member revise/withdraw and requires organizer confirmation even after consensus");
  await page.reload(); await page.getByRole("heading",{name:"Sessioni",exact:true,level:1}).waitFor();
  state = await stored();
  check(state.campaign.sessions.length === before.campaign.sessions.length + 2, "Reload duplicated confirmed session");
  await page.screenshot({path:"/Users/salvatoredicara/Workspace/Codex/d20-blueprint-evidence/2026-09-23/campaign-sessions-desktop-it.png",fullPage:true});
  check(errors.length === 0, "Runtime errors: " + errors.join("; "));
  return {passed,errors};
}
