// Dark theme only, as direction.css: under the light theme every icon stays the core one (the
// app re-renders on a theme change, so the override is asked again).
function lightTheme() {
  try {
    return globalThis.document?.documentElement?.getAttribute("data-pref-theme") === "light";
  } catch {
    return false;
  }
}

export function directionIcon(name) {
  const glyph = Object.hasOwn(ICONS, name) ? ICONS[name] : null;
  if (!glyph || lightTheme()) return null;
  return `<svg class="icon" viewBox="${glyph[0]}" fill="currentColor" stroke="none" aria-hidden="true">${glyph[1]}</svg>`;
}
