const LINE = "1.4";
const GROOVE = "2.2";

function engraved(name, body) {
  return (
    `<svg class="icon" data-icon="${name}" data-icon-voice="i2" viewBox="0 0 24 24" fill="none" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">` +
    `<g class="icon-shadow" stroke="rgb(0 0 0 / 0.72)" stroke-width="${GROOVE}" transform="translate(0 -0.6)">${body}</g>` +
    `<g style="stroke:color-mix(in srgb, currentColor var(--i2-keep, 40%), #f2deaa)" stroke-width="${LINE}">${body}</g></svg>`
  );
}

export function directionIcon(name) {
  if (name === "dice")
    return iconPath("dice") ? engraved(name, `<path d="${iconPath("dice")}"/>`) : null;
  const glyph = Object.hasOwn(GLYPHS, name) ? GLYPHS[name] : null;
  return glyph ? engraved(name, glyph[1]) : null;
}
